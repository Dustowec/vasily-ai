"""Токенизация и стемминг для retrieval памяти (Шаг 2 Задачи №2, ADR-013 §9).

Проблема: substring-поиск ("кот" in "который") даёт ложные срабатывания
и пропускает словоформы ("коты" не находит "кот").

Решение: разбиваем текст на слова, приводим к основе стеммером Snowball
для русского, сравниваем множества основ. Стемминг даёт морфологию
без словарей (в отличие от pymorphy3) и без внешних сервисов.

Почему не BM25 / FTS5:
  - корпус памяти ≤ 70 записей — O(N) мгновенен, BM25 не нужен;
  - релевантность по смыслу уже даёт LLM-ранк (Задача №3);
  - русская морфология у FTS5 из коробки отсутствует, всё равно
    пришлось бы тянуть стеммер.

Публичный API:
  tokenize(text) -> set[str]        — множество основ слов;
  matches(query, text) -> bool      — есть ли общая основа.
"""

import re

import snowballstemmer

# блок: стеммер Snowball для русского — singleton.
# почему: создание stemmer'а каждый раз дорого (загружается словарь
# правил), а сам объект stateless и потокобезопасен для чтения.
# Один экземпляр на процесс — оптимально.
_STEMMER = snowballstemmer.stemmer("russian")

# блок: регексп для разбивки текста на слова.
# почему: \w в Python-регекспе с re.UNICODE матчит буквы любого
# алфавита, включая кириллицу. Цифры и _ тоже попадают — это
# нормально, "user_fact:123" разобьётся на "user", "fact", "123".
_WORD_RE = re.compile(r"\w+", re.UNICODE)


def tokenize(text) -> set[str]:
    """Разбивает текст на множество основ слов.

    - None / пустая строка → пустое множество;
    - регистр снимается ДО стемминга (Snowball сохраняет регистр,
      поэтому "Котофей" и "котофей" без .lower() дали бы разные основы);
    - результат — set[str]: дедупликация + O(1) пересечение.
    """
    # блок: защита от None и пустых значений.
    # почему: retrieval получает данные из JSON и из запроса LLM;
    # любой из них может оказаться None или пустой строкой.
    if not text:
        return set()

    # блок: приведение к строке и lowercase.
    # почему: .lower() обязателен перед стеммером — иначе "Котофей"
    # → "Котоф", а "котофей" → "котоф", и они не совпадут.
    text = str(text).lower()

    # блок: разбивка на слова + стемминг каждого.
    # почему: set comprehension дедуплицирует повторяющиеся основы
    # (текст "кот кота коту" → {"кот"}).
    return {_STEMMER.stemWord(w) for w in _WORD_RE.findall(text)}


def matches(query_tokens: set[str], text_tokens: set[str]) -> bool:
    """True, если у query и text есть хотя бы одна общая основа.

    Контракт: оба аргумента — множества из tokenize().
    Пустое множество с любой стороны → False.
    """
    # блок: пересечение множеств.
    # почему: вместо substring-проверки "кот" in "который" (True)
    # сравниваем нормализованные основы: {"кот"} ∩ {"котор"} = ∅ (False).
    return bool(query_tokens & text_tokens)
