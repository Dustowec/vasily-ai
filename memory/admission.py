"""Admission gate: фильтр на секреты ПЕРЕД записью в память (Шаг 3 Задачи №2).

Проблема: пользователь (или LLM через remember_fact) может попытаться
сохранить "мой пароль: hunter2". Такое значение уйдёт в JSON-файл
памяти и останется там навсегда — компрессия его не уберёт.

Решение: regex-фильтр, срабатывающий в единственной точке — в
manager._store_entry. Никто не обойдёт: ни инструмент, ни фоновая
компрессия диалога, ни будущие пути записи.

Что фильтруем:
  - пары "ключ: значение" с явно секретными ключами
    (password, пароль, token, api_key, ...);
  - "Bearer <token>", если <token> содержит цифры или длину 20+;
  - префиксные токены популярных провайдеров (sk-, ghp_, AIza, ...);
  - длинные base64-подобные строки (40+ символов) со смешанным
    регистром и цифрами (монотонные "xxxx" отсеиваются).

Что НЕ фильтруем (сознательно):
  - "эфемерное" (погода, время, курс) — слишком много ложных
    срабатываний: "люблю когда холодно" — это предпочтение, не мусор;
  - обычные числа, имена, города, даты;
  - длинные русские слова/фразы (regex работает только по [A-Za-z0-9+/=]).

Публичный API:
  check_admission(value) -> str | None
    None — можно писать;
    str  — причина блокировки (машиночитаемая):
           "secret_key_pair" | "bearer_token" | "token_prefix"
           | "long_random_string".

Где вызывается:
  - GradientMemory._store_entry (единственный гейт для всех путей).
"""

import re

# блок: пары "секретный_ключ: значение".
# почему: типичный сценарий — LLM записывает "запомни мой пароль к X: yyy".
# Регикс требует и ключевое слово, и разделитель (двоеточие или =),
# чтобы не ловить обычный текст "я забыл пароль" без значения.
# (?i) — регистронезависимо, \b — границы слова.
_SECRET_KEY_PAIRS = re.compile(
    r"(?i)\b("
    r"password|passwd|pwd|passphrase|"
    r"secret|token|"
    r"api[_\s-]?key|access[_\s-]?key|auth[_\s-]?token|"
    r"пароль|токен"
    r")\s*[:=]\s*\S+"
)

# блок: "Bearer <token>" — отдельный паттерн.
# почему: Bearer пишется через ПРОБЕЛ, а не через ':' или '='.
# В _SECRET_KEY_PAIRS он был бы неуместен — там все ключи с разделителем.
# ВАЖНО: захватываем ТОКЕН в группу, а не просто матчим "Bearer + слово".
# Настоящий токен отличим от английского слова по наличию цифр или длине.
_BEARER = re.compile(r"(?i)\bBearer\s+(\S+)")

# блок: токены популярных провайдеров по префиксу.
# почему: даже без ключевого слова рядом "sk-abc..." — это почти
# наверняка OpenAI-ключ. Ловим по узнаваемому префиксу + длине.
_TOKEN_PREFIXES = re.compile(
    r"\b("
    r"sk-[A-Za-z0-9]{20,}"  # OpenAI
    r"|ghp_[A-Za-z0-9]{30,}"  # GitHub personal access
    r"|gho_[A-Za-z0-9]{30,}"  # GitHub oauth
    r"|xoxb-[A-Za-z0-9-]{20,}"  # Slack bot
    r"|AIza[A-Za-z0-9_-]{30,}"  # Google API
    r")\b"
)

# блок: длинные base64-подобные строки.
# почему: 40+ символов из [A-Za-z0-9+/=] — это, с высокой вероятностью,
# случайный токен/хеш/секрет, а не слово. Русский текст такой длины —
# редкость (кириллица не входит в этот алфавит).
# ВАЖНО: один регексп ловит И "xxxxx...", И реальные токены. Различить
# их — задача отдельной проверки _is_random_looking (см. ниже).
_LONG_RANDOM = re.compile(r"[A-Za-z0-9+/=]{40,}")


def _is_random_looking(s: str) -> bool:
    """Похожа ли строка на случайный токен, а не на повторяющийся символ.

    Настоящий токен содержит смесь строчных, прописных и цифр.
    "xxxxx...xxxx" (монотонный) или "aaaaaaaaaa" — это не токен,
    а тестовая заглушка или ручной текст.
    """
    return (
        any(c.islower() for c in s)
        and any(c.isupper() for c in s)
        and any(c.isdigit() for c in s)
    )


def check_admission(value) -> str | None:
    """Проверяет значение на признаки секрета. Возвращает reason или None.

    Args:
        value: любое — str, dict, число, None. Не-str приводится к str.

    Returns:
        None — можно писать в память;
        str  — машиночитаемая причина блокировки:
               "secret_key_pair" | "token_prefix" | "long_random_string".
    """
    # блок: None и пустоту пропускаем без проверок.
    # почему: они не несут информации, отдельно обрабатываются вызывающим
    # кодом до gate'а. Гейт отвечает только на вопрос "секрет?".
    if value is None:
        return None

    text = str(value)
    if not text.strip():
        return None

    # блок: проверки от самого точного к самому широкому.
    # почему: "secret_key_pair" / "bearer_token" дают лучшую диагностику,
    # чем "long_random_string". Порядок имеет значение.
    if _SECRET_KEY_PAIRS.search(text):
        return "secret_key_pair"

    # блок: Bearer <token> блокируем только если <token> похож на токен.
    # почему: "Bearer authentication" — обычная фраза, не секрет.
    # Настоящий JWT/OAuth-токен содержит цифры (смешанный регистр
    # не гарантирован для коротких токенов) ИЛИ длинный (20+).
    bearer_match = _BEARER.search(text)
    if bearer_match:
        token = bearer_match.group(1)
        if any(c.isdigit() for c in token) or len(token) >= 20:
            return "bearer_token"

    if _TOKEN_PREFIXES.search(text):
        return "token_prefix"

    # блок: "long_random" требуёт дополнительной проверки на смешанный регистр.
    # почему: regex [A-Za-z0-9+/=]{40,} ловит "x"*200 — а это заглушка,
    # не секрет. Настоящий токен содержит И строчные, И прописные, И цифры.
    for m in _LONG_RANDOM.finditer(text):
        if _is_random_looking(m.group(0)):
            return "long_random_string"

    return None
